/** Повне коло, що починається й закінчується в куті start. */
function lap(start: number): [number, number][] {
  const out: [number, number][] = [];
  for (let i = 0; i <= RING.length; i++) out.push(RING[(start + i) % RING.length]);
  return out;
}

