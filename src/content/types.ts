/** Стабільний ідентифікатор башти. Змінювати не можна — він у протоколі. */
export type ToolKey = string;

/** Лише для угруповання в інтерфейсі. Ядро це поле не читає — доступ
 *  вирішує набір гравця, а не напис на башті. */
export type FactionKey = 'any' | 'steel' | 'ice' | 'fire' | 'toxic';

/* Рівень башти. Відкривається по ходу партії, однаково для всіх фракцій:
   1 — з початку, 2 — з хвилі TIER_WAVE[2], 3 — з TIER_WAVE[3].

   Паритет тримається ПОТИРНЕВО, а не сумарно. Це не педантизм: коли
   гравець зможе поєднувати фракції, сумарний паритет дозволив би зібрати
   «найкраще з кожної», а потирневий лишає вибір змістовним — башти того
   самого рівня рівноцінні, різні лише способом. */
export type Tier = 1 | 2 | 3;

/* Рівні навмисно НЕ прив'язані до босів (ті стоять на 10, 15, 20).

   Спершу вони збігались — середні з 5 і бос на 5, топові з 10 і бос на
   10. Це робило боса шлагбаумом: гра вимагала купити щойно відкриту
   башту, бо іншої відповіді не було. Рішення без альтернативи — не
   рішення, а податок.

   Тепер відкриття — власна подія в темпі гри: нова можливість, яку можна
   взяти або відкласти на користь ширшої забудови. */
export const TIER_WAVE: Record<Tier, number> = { 1: 0, 2: 5, 3: 12 };

export const TIER_NAME: Record<Tier, string> = { 1: 'базові', 2: 'середні', 3: 'топові' };

/** Найвищий рівень, доступний на цій хвилі. */
export function tierAt(wave: number): Tier {
  if (wave >= TIER_WAVE[3]) return 3;
  if (wave >= TIER_WAVE[2]) return 2;
  return 1;
}

export interface Tool {
  key: ToolKey;
  faction: FactionKey;
  tier: Tier;
  name: string;
  cost: number;
  /** Шкода за постріл на 1-му рівні. */
  dmg: number;
  /** Перезарядка в тіках. */
  cd: number;
  /** Радіус у під-одиницях (задавати через tiles()). */
  range: number;
  /** Швидкість снаряда; 0 — не стріляє. */
  shot: number;
  /** CSS-змінна кольору. */
  swatch: string;
  blurb: string;
  /** Позиція в арсеналі. Проставляється реєстром, у контенті не пишеться. */
  slot: number;

  /** Радіус, у якому постріл завдає ШКОДИ всім. */
  splash?: number;
  /** Радіус, у якому постріл накладає свій ЕФЕКТ (мороз, отруту) — без
   *  шкоди. Окремо від splash: башта може бити одну ціль, а студити всіх
   *  поруч. Це вісь Криги: холод розходиться. */
  spread?: number;
  slow?: number;
  slowT?: number;
  dot?: number;
  dotT?: number;

  /* Позначає ціль: доки позначка тримається, крип отримує на стільки
     відсотків БІЛЬШЕ шкоди від будь-кого.

     Це те, заради чого допоміжна фракція взагалі існує. Без позначки вона
     змагалася з основною на тій самій мірці — шкода на золото — і
     програвала: прогін показав, що добра гра не купувала допоміжних веж
     узагалі (0 із 151). Позначка робить її множником до основної, а не
     конкурентом їй.

     Мають її ЛИШЕ допоміжні. Інакше Вогонь позначав би цілі власним
     підпалом і знову обходився б без допоміжної.

     Тривалість позначки — це тривалість самого ефекту вежі, тож вісь
     характеру та сама: Крига позначає коротко й сильно, Отрута довго
     й слабко. */
  mark?: number;

  /** Має сенс лише там, де гравець сам будує трасу. На фіксованому шляху
   *  така башта не робить НІЧОГО — траса незмінна, перекривати нічого, —
   *  тож там її не пропонують і не дозволяють ставити. */
  mazeOnly?: boolean;
}

/** Те, що не є баштою, але сидить у тій самій панелі: знос, прокачка, приціл. */
export type CursorMode = 'raze' | 'up' | 'aim';

/** Що зараз тримає гравець у руці. */
export type Cursor = Tool | CursorMode;

export const isTool = (c: Cursor): c is Tool => typeof c !== 'string';

/* ── набори арсеналу ─────────────────────────────────────────────────
   Набір — це НЕ окремі башти, а дозвіл на підмножину спільного реєстру.
   Так башта завжди означає те саме в усіх гравців (і в хеші звірки), а
   набір лише вирішує, кому вона доступна. Завдяки цьому «стартовий +
   набутий» — це просто об'єднання множин, і його можна розширювати
   під час партії, не ламаючи детермінізм.                              */
/** Основна дає хребет шкоди, допоміжна — контроль. Гравець бере по одній
 *  кожного роду, тож комбінацій рівно (основні × допоміжні). */
export type Role = 'primary' | 'support';

export interface Loadout {
  key: string;
  role: Role;
  name: string;
  blurb: string;
  /** Ключі з реєстру TOOLS. Порядок = порядок кнопок в арсеналі. */
  tools: ToolKey[];
}

/* ── хвилі ───────────────────────────────────────────────────────────── */
export interface WaveBody {
  /** Скільки крипів. */
  n: number;
  hp: number;
  /** Швидкість у під-одиницях за тік. */
  sp: number;
  /** Золото за вбивство (табличне, до killCut). */
  gold: number;
  /** Індекс у KIND_NAME/ARMOR. */
  kind: number;
}

export interface WaveSpec extends WaveBody {
  /** Супровід боса — іде разом із ним. */
  esc?: WaveBody;
}

/* ── мапи ────────────────────────────────────────────────────────────── */
export interface MapDef {
  name: string;
  note: string;
  /** Вейпойнти траси; між сусідніми — рівний відрізок по осі. */
  road: [number, number][];
  /** Прямокутники скель: [x, y, w, h]. */
  rocks: [number, number, number, number][];
  /** Припущене покриття в режимі лабіринту; якщо немає — береться з BALANCE. */
  mazeCov?: number;
}
