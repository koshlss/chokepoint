import { SUB, TPS } from '../sim/constants';
import { UPG } from './towers';
import type { Tool } from './types';

/* ══════════════════════════════════════════════════════════════════════
   МІРА СИЛИ — єдина величина, за якою балансується весь контент.

   Навіщо. Без неї кожна нова вежа означає повний прогін бота й півдня
   підбору чисел, і так за кожну зміну. З нею нова вежа перевіряється
   формулою за секунду, а прогін лишається для перевірки САМОЇ МОДЕЛІ,
   а не кожної правки.

   Що це. power(t) — скільки вежа варта за секунду, зведене до однієї
   шкали: пряма шкода, площа, отрута й контроль в одних одиницях.
   Далі все зводиться до двох чисел:

     віддача  = power / ціна     — скільки сили за одиницю золота
     сила     = power            — скільки сили з ОДНІЄЇ клітини

   і трьох правил, які тримають гру цікавою. Кожне з них — не смак, а
   висновок із виміряного:

   ── ПРАВИЛО 1 · рівна віддача всередині рівня ────────────────────────
   Замір показав розкид 0.28–0.53 серед базових Сталі. Наслідок: Мортиру
   (0.28) не будували НІКОЛИ, на всіх дошках був самий Стріломет. Коли
   одна вежа рівня вдвічі вигідніша за іншу, вибору немає — є арифметика.
   Тому віддача всередині рівня має лежати у вузькій смузі, а різнитись
   вежі мають дальністю, площею та ефектом.

   ── ПРАВИЛО 2 · сила росте з рівнем ──────────────────────────────────
   Клітини вздовж траси скінченні. Коли вони заповнені, додати шкоди
   можна лише сильнішою вежею на тій самій клітині. Тому абсолютна сила
   має рости від рівня до рівня — інакше дорогі вежі не потрібні ніколи.

   ── ПРАВИЛО 3 · прокачка НЕ вигідніша за нову вежу ───────────────────
   Це та вада, через яку всі чотири комбінації грались однаково. Прокачка
   давала +110% шкоди за 90% ціни — тобто була вигідніша за нову вежу
   (1.22×) І ще й не займала клітину. Виграшна стратегія завжди одна:
   заставити хороші клітини найдешевшим і вкачати. Форма партії ставала
   незалежною від фракції.

   Тепер прокачка коштує ТРОХИ БІЛЬШЕ, ніж дає: це плата за економію
   клітини. Хочеш більше шкоди за ті самі гроші — став нову вежу; хочеш
   більше шкоди на тій самій клітині — доплати.
   ══════════════════════════════════════════════════════════════════════ */

/* ── калібрувальні константи ──────────────────────────────────────────
   Це не вільні параметри, а знята з гри мірка. Міняти їх можна лише
   разом із перевіркою bench/calibration — інакше модель почне брехати. */

/** Отрута тікає раз на стільки тіків (Sim: c.dotCd = 15). */
const DOT_PERIOD = 15;
/** Крип не піддається морозу стільки тіків після того, як той спав. */
const SLOW_IMMUNE = 20;
/** Дальність, відносно якої міряється досяжність. Приблизна середина. */
const REF_RANGE_TILES = 3.0;
/** Довжина типової траси в кроках — «Двійка» має 73. */
const REF_PATH_STEPS = 73;
/** Шкода за секунду армії, яку множить контроль. Знято з прогонів:
 *  у середині партії дошка тримає близько двадцяти веж. */
const ARMY_REF = 4000;
/** Отрута йде крізь броню, тож коштує трохи більше за таку саму пряму. */
const DOT_BONUS = 1.3;

/** Пряма шкода за секунду. */
export const directDps = (t: Tool, dmg = t.dmg) => (t.cd ? (dmg * TPS) / t.cd : 0);

/* Скільки крипів накриває вибух.

   Доти модель рахувала радіус як є: area = 1 + радіус. Замір на 10 тисячах
   пострілів показав, що це неправда, і найгрубіше — на малих радіусах:

     Картеч  радіус 0.60  модель ×1.60  насправді ×1.02
     Мортира радіус 1.10  модель ×2.10  насправді ×1.22
     Гармата радіус 1.35  модель ×2.35  насправді ×1.77
     Вогнище радіус 1.40  модель ×2.40  насправді ×2.19

   Крипи йдуть розтягнуто, і радіус, менший за проміжок між ними, не ловить
   нікого зайвого — Картеч фактично одноцільна. Модель платила Сталі за
   площу, якої та не отримує, і це вилилось у три хвилі відставання від
   Вогню, чия найдешевша вежа площі не має взагалі й тому була оцінена
   правильно.

   Тому зараховуємо лише ту частину радіуса, що перевищує типовий проміжок
   між крипами. */
const SPLASH_FLOOR = 0.55 * SUB;
const area = (t: Tool) =>
  1 + (t.splash ? Math.max(0, t.splash - SPLASH_FLOOR) / SUB : 0);

/** Наскільки довше вежа тримає ціль під вогнем за рахунок дальності. */
const reach = (t: Tool) => (t.range ? t.range / SUB / REF_RANGE_TILES : 0);

/** Частка траси, яку вежа дістає. Пряма ділянка під радіусом ≈ 2×радіус. */
const pathShare = (t: Tool) =>
  Math.min(1, (2 * (t.range / SUB)) / REF_PATH_STEPS);

/** Частка часу, яку ефект справді діє. Мороз має вікно несприйнятливості,
 *  тління — ні, тож воно тримається безперервно. */
const slowUptime = (t: Tool) => (t.slowT ? t.slowT / (t.slowT + SLOW_IMMUNE) : 0);

/** Скільки вежа додає ВСІЙ армії — сповільненням і позначкою. Це і є
 *  цінність допоміжних: вони не б'ють, вони множать. */
export function control(t: Tool): number {
  const slowPart = ((t.slow || 0) / 100) * slowUptime(t);
  const markPart = ((t.mark || 0) / 100) * (t.mark ? slowUptime(t) || 1 : 0);
  return (slowPart + markPart) * ARMY_REF * pathShare(t);
}

/** Скільки вежа варта за секунду ВЛАСНОЮ шкодою. */
export function power(t: Tool, dmg = t.dmg): number {
  if (!t.shot) return 0;                       // бар'єр не б'є й не множить
  const dot = t.dot ? (t.dot * TPS) / DOT_PERIOD : 0;
  return reach(t) * (directDps(t, dmg) * area(t) + dot * DOT_BONUS);
}

/** Скільки цілей накриває ОДНЕ накладання ефекту. Для допоміжних це те
 *  саме, чим area() є для шкоди: пляма (spread) чіпляє сусідів без
 *  шкоди, вибух (splash) — разом зі шкодою, тож рахується більший. */
const effectArea = (t: Tool) =>
  1 + Math.max(t.splash || 0, t.spread || 0) / SUB;

/** Чим МІРЯЮТЬСЯ ГІЛКИ допоміжних.
 *
 *  Окремо від control() навмисно: control() і його смуга калібровані на
 *  вежах як таких, і чіпати їх заради прокачки означало б переставити
 *  весь наявний баланс. Тут інша задача — порівняти дві гілки ОДНІЄЇ
 *  вежі між собою, а для цього потрібен саме той доданок, якого в
 *  control() немає: ширина плями. Без нього «ширше морозить» читалось
 *  як чиста втрата, бо модель бачила лише просілу шкоду. */
export const supportValue = (t: Tool) => control(t) * effectArea(t);

/** Сила на одиницю ціни. Головне число правила 1.
 *
 *  Навмисно рахує ЛИШЕ шкоду, без контролю. Контроль має насичення —
 *  позначки не складаються, трасу достатньо покрити один раз, — тож
 *  ділити його на ціну однієї вежі означало б приписати шостій крижаній
 *  вежі ту саму цінність, що й першій. Контроль перевіряється окремо. */
export const efficiency = (t: Tool) => power(t) / t.cost;

/** Скільки контролю вежа дає на одиницю ціни. Для допоміжних це головне
 *  число; смуга своя, бо це інший товар. */
export const controlPerGold = (t: Tool) => control(t) / t.cost;

/** Сукупна ціна вежі, вкачаної до рівня lvl. */
export function totalCost(t: Tool, lvl: number): number {
  let c = t.cost;
  for (let l = 2; l <= lvl; l++) c += (t.cost * UPG[l]!.pct) / 100;
  return c;
}

/** Віддача вежі, вкачаної до рівня lvl. Правило 3 вимагає, щоб вона
 *  не РОСЛА з рівнем. */
export function efficiencyAt(t: Tool, lvl: number): number {
  const dmg = ((t.dmg * UPG[lvl]!.dmg) / 100) | 0;
  return power(t, dmg) / totalCost(t, lvl);
}

/* ── смуги, у які має влучати новий контент ───────────────────────────
   Основні й допоміжні міряються окремо: перші продають шкоду, другі —
   множник. Порівнювати їх однією смугою означало б знову зробити
   допоміжну або зайвою, або обов'язковою. */
export const BAND = {
  /** Основні продають шкоду — їхня віддача має лежати у вузькій смузі,
   *  інакше всередині рівня лишається одна вежа, а решта мертві. */
  /* Центр смуги задає СКЛАДНІСТЬ усієї гри — це одне число, яким
     піднімають чи опускають планку, не чіпаючи співвідношень. Ширина
     смуги задає СВОБОДУ ВИБОРУ: чим вона вужча, тим менше значить
     арифметика й більше — дальність, площа та ефект. */
  damage: { min: 0.42, max: 0.70 },
  /** Допоміжні продають множник. Власна шкода в них має бути помітно
   *  НИЖЧОЮ за смугу основних — інакше їх купують замість зброї, і саме
   *  це сталось із Кріостатом: 0.50 проти 0.49 у Стрілометі, тобто
   *  допоміжна виявилась кращою бойовою, ніж бойові. */
  supportDamageMax: 0.32,
  /** А от контролю вони мають давати співмірно між собою — інакше одна
   *  допоміжна просто краща за іншу. */
  control: { min: 1.0, max: 2.4 },
};

/* ── СХОДИНКА ВІДДАЧІ ЗА РІВНЕМ ───────────────────────────────────────
   Доти віддача була однакова на ВСІХ рівнях — 0.53–0.59 у кожної вежі
   від найдешевшої до найдорожчої. Замір «доброї гри» показав, у що це
   виливається: Вогонь ставив 82% дошки однією Іскрою (106 веж за партію),
   а Мортира, Гармата, Горнило й Жаровня не будувались ЖОДНОГО разу.

   І це не вада бота, а правильна арифметика. Дорога вежа коштує більше,
   відкривається пізніше, довше будується й позбавляє гнучкості — а дає
   рівно стільки ж сили на золото. Купувати вгору не було жодної причини.

   Задум спирався на те, що клітини вздовж траси скінченні й рано чи пізно
   змусять брати сильніше. На практиці не змушують: місць вистачає на сто
   веж.

   Тому віддача тепер РОСТЕ з ціною: це і є плата за очікування,
   негнучкість і час будівництва.

   Сходинка йде за ЦІНОЮ, а не за рівнем. Перша спроба зробила її за
   рівнем — і всередині рівня повторилась та сама вада: за рівної віддачі
   виграє найдешевша вежа, тож Сталь просто перейшла з Іскри на Картеч
   (52% дошки), а Мортира, Гармата й Жаровня так і лишились нулями. Ціна
   ж міряє те саме, що й рівень, тільки без сходинок: дорожча вежа менш
   гнучка, довше будується й вимагає накопичити — і за це отримує більше
   сили на золото. Дешева нікуди не дівається: вона те, що по кишені
   зараз, і те, чим добирають решту золота. */
const EFF_BASE = 0.455;   // віддача найдешевшої вежі (45 золота) — і головне число складності
const EFF_SLOPE = 0.135;  // наскільки круто вона росте з ціною
export const targetEff = (cost: number) => EFF_BASE * Math.pow(cost / 45, EFF_SLOPE);
/** Наскільки віддача вежі може відхилятись від своєї сходинки. */
export const TIER_EFF_TOL = 0.05;

/** У скільки разів сила однієї вежі росте від рівня до рівня.
 *  Правило 2: клітини скінченні, тож дорога вежа має щось давати. */
/* Не вільне число: за правилом 1 сила пропорційна ціні, тож крок між
   рівнями заданий сходинками цін (170 → 380 → 620, тобто 2.2× і 1.6×).
   Округлення цілої шкоди трохи його зсуває, звідси запас. */
export const TIER_STEP_MIN = 1.5;

/* ── ЧАС БУДІВНИЦТВА ──────────────────────────────────────────────────
   Третій ресурс поруч із золотом і клітинами: вежа не стріляє, поки
   будується.

   Виводиться прямо з ціни — і це не спрощення, а наслідок правила 1:
   раз віддача на золото однакова, то ціна ПРОПОРЦІЙНА силі, тож час,
   пропорційний ціні, автоматично пропорційний і вигоді від вежі.

   Що це дає грі: пауза між хвилями перестає бути безмежним вікном для
   покупок. Поставити п'ять дешевих і поставити одну важку — тепер різні
   рішення не лише за золотом, а й за тим, скільки з них устигне
   вистрілити цієї хвилі. І це саме той важіль, якого бракувало проти
   спаму найдешевшою баштою. */
const BUILD_BASE = 12;      // тіків навіть на найдешевшу — щоб клік не був миттєвим
const BUILD_PER_GOLD = 3;   // скільки золота ціни дає один тік будівництва

export function buildTicks(cost: number): number {
  return BUILD_BASE + ((cost / BUILD_PER_GOLD) | 0);
}
