const TPS  = 30;      // тіків на секунду
const SUB  = 256;     // під-одиниць у клітині
const GW   = 26, GH = 18;

const idx = (x, y) => y * GW + x;

const MODE_MAZE = 0, MODE_FIXED = 1;

/* Радіуси задаються В КЛІТИНАХ через tiles() — раніше вони були вписані
   сирими під-одиницями й виходили втричі коротшими, ніж задумано. */
const tiles = n => Math.round(n * SUB);

export { TPS, SUB, GW, GH, idx, MODE_MAZE, MODE_FIXED, tiles };
